// Emits SVG path data for "K76" set in Anton (used by the Loader + Logo).
import fs from 'node:fs';
import opentype from 'opentype.js';
const [, , input, output] = process.argv;
const buf = fs.readFileSync(input);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const size = 100, tracking = 4;
let x = 0; const parts = [];
for (const ch of 'K76') {
  const g = font.charToGlyph(ch);
  const p = g.getPath(x, 100, size);
  const bb = p.getBoundingBox();
  parts.push({ ch, d: p.toPathData(2), bb });
  x += (g.advanceWidth / font.unitsPerEm) * size + tracking;
}
const minX = Math.min(...parts.map(p => p.bb.x1)), maxX = Math.max(...parts.map(p => p.bb.x2));
const minY = Math.min(...parts.map(p => p.bb.y1)), maxY = Math.max(...parts.map(p => p.bb.y2));
const viewBox = `${minX.toFixed(1)} ${minY.toFixed(1)} ${(maxX-minX).toFixed(1)} ${(maxY-minY).toFixed(1)}`;
const src = `// Generated by scripts/make-logo-path.mjs from Anton (OFL). Do not edit by hand.
export const LOGO_VIEWBOX = '${viewBox}'
export const LOGO_PATHS = ${JSON.stringify(parts.map(p => ({ ch: p.ch, d: p.d })), null, 2)} as const
`;
fs.writeFileSync(output, src);
console.log(viewBox, src.length);
